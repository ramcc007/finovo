// Generates src/lib/election/usMap.ts: SVG paths for the 50 states + DC from the public-domain US Atlas
// (already projected to a 975 x 610 Albers USA layout). Run: node scripts/gen-us-map.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoPath } from 'd3-geo';

const NAME_TO_CODE = {
  Alabama: 'AL', Alaska: 'AK', Arizona: 'AZ', Arkansas: 'AR', California: 'CA', Colorado: 'CO', Connecticut: 'CT', Delaware: 'DE',
  'District of Columbia': 'DC', Florida: 'FL', Georgia: 'GA', Hawaii: 'HI', Idaho: 'ID', Illinois: 'IL', Indiana: 'IN', Iowa: 'IA',
  Kansas: 'KS', Kentucky: 'KY', Louisiana: 'LA', Maine: 'ME', Maryland: 'MD', Massachusetts: 'MA', Michigan: 'MI', Minnesota: 'MN',
  Mississippi: 'MS', Missouri: 'MO', Montana: 'MT', Nebraska: 'NE', Nevada: 'NV', 'New Hampshire': 'NH', 'New Jersey': 'NJ',
  'New Mexico': 'NM', 'New York': 'NY', 'North Carolina': 'NC', 'North Dakota': 'ND', Ohio: 'OH', Oklahoma: 'OK', Oregon: 'OR',
  Pennsylvania: 'PA', 'Rhode Island': 'RI', 'South Carolina': 'SC', 'South Dakota': 'SD', Tennessee: 'TN', Texas: 'TX', Utah: 'UT',
  Vermont: 'VT', Virginia: 'VA', Washington: 'WA', 'West Virginia': 'WV', Wisconsin: 'WI', Wyoming: 'WY',
};

const topo = JSON.parse(readFileSync('node_modules/us-atlas/states-albers-10m.json', 'utf8'));
const path = geoPath().digits(1);
const states = feature(topo, topo.objects.states).features.map(f => {
  const name = f.properties.name;
  const code = NAME_TO_CODE[name];
  if (!code) throw new Error(`Unknown state: ${name}`);
  const [cx, cy] = path.centroid(f);
  const [[x0, y0], [x1, y1]] = path.bounds(f);
  return { code, name, d: path(f), cx: Math.round(cx), cy: Math.round(cy), w: Math.round(x1 - x0), h: Math.round(y1 - y0) };
}).sort((a, b) => a.code.localeCompare(b.code));
if (states.length !== 51) throw new Error(`Expected 51 states, got ${states.length}`);

const out = `// Generated by scripts/gen-us-map.mjs from the public-domain US Atlas. Do not edit by hand.
export const MAP_VIEWBOX = '0 0 975 610';
export interface MapState { code: string; name: string; d: string; cx: number; cy: number; w: number; h: number }
export const US_STATES: MapState[] = ${JSON.stringify(states)};
`;
writeFileSync('src/lib/election/usMap.ts', out);
console.log('states:', states.length, '| bytes:', out.length);
