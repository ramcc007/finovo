-- Bulk and block deals from NSE's daily files, for the stock page. History builds up from the first run.
create table if not exists public.bulk_deals (
  id bigint generated by default as identity primary key,
  trade_date date not null,
  symbol text not null,
  client text not null,
  side text not null check (side in ('BUY','SELL')),
  quantity bigint not null,
  price numeric(14,2),
  deal_type text not null check (deal_type in ('bulk','block')),
  created_at timestamptz not null default now()
);
create unique index if not exists bulk_deals_uniq on public.bulk_deals (trade_date, symbol, client, side, quantity, deal_type);
create index if not exists bulk_deals_symbol_idx on public.bulk_deals (symbol, trade_date desc);
alter table public.bulk_deals enable row level security;
drop policy if exists "Public read bulk_deals" on public.bulk_deals;
create policy "Public read bulk_deals" on public.bulk_deals for select using (true);
