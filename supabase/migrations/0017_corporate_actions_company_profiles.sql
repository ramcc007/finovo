-- corporate_actions: the table scripts/ingest_corporate_actions.py has always written to but which
-- was never created, so the stock page section was empty and the daily job failed.
create table if not exists public.corporate_actions (
  id bigint generated by default as identity primary key,
  symbol text not null,
  action_type text not null,
  ex_date date,
  record_date date,
  bc_start_date date,
  bc_end_date date,
  purpose text not null,
  created_at timestamptz not null default now()
);
create unique index if not exists corporate_actions_uniq on public.corporate_actions (symbol, action_type, ex_date, purpose) nulls not distinct;
create index if not exists corporate_actions_symbol_idx on public.corporate_actions (symbol, ex_date desc);
alter table public.corporate_actions enable row level security;
drop policy if exists "Public read corporate_actions" on public.corporate_actions;
create policy "Public read corporate_actions" on public.corporate_actions for select using (true);

-- company_profiles: business summary, website, employees, head office and key officers
-- (scripts/ingest_company_profiles.py, from Yahoo Finance).
create table if not exists public.company_profiles (
  symbol text primary key,
  summary text,
  website text,
  employees integer,
  city text,
  state text,
  country text,
  officers jsonb not null default '[]'::jsonb,
  source text not null default 'Yahoo Finance',
  updated_at timestamptz not null default now()
);
alter table public.company_profiles enable row level security;
drop policy if exists "Public read company_profiles" on public.company_profiles;
create policy "Public read company_profiles" on public.company_profiles for select using (true);

